const record={kind:'spend',campaignKey:PILOT_KEY,amountMinor:300,currency:'USD',effectiveAt:'2026-11-01T05:00:00.000Z',coverageStartUtc:'2026-11-01T05:00:00.000Z',coverageEndUtc:'2026-11-02T06:00:00.000Z',sourceRef:'reviewed_export_fixture',authority:'actual',coverage:'complete'};
test('cost evidence refuses private data and incomplete coverage contracts',()=>{
  assert.ok(CostEvidenceSchema.safeParse(record).success);
  assert.equal(CostEvidenceSchema.safeParse({...record,email:'private@example.com'}).success,false);
  assert.equal(CostEvidenceSchema.safeParse({...record,sourceRef:'https://private.example/letter'}).success,false);
  assert.equal(CostEvidenceSchema.safeParse({...record,coverageEndUtc:undefined}).success,false);
});
test('reviewed CSV import validates campaign identity, dates, currency, counts and formulas',()=>{
  const good='campaign_id,date,impressions,clicks,spend,currency\n24457739017,2026-11-09,100,2,10.25,USD';
  const rows=parseSpendCsv(good,'spend',PILOT_KEY,'reviewed_ads_export_1');
  assert.equal(rows[0].kind,'spend');
  assert.equal(rows[0].amountMinor,1025);
  assert.equal(rows[0].clicks,2);
  assert.equal(Date.parse(rows[0].coverageEndUtc)-Date.parse(rows[0].coverageStartUtc),24*60*60*1000);
  assert.throws(()=>parseSpendCsv(good.replace('24457739017','999'), 'spend',PILOT_KEY,'reviewed_ads_export_1'),/CAMPAIGN_ID_MISMATCH/);
  assert.throws(()=>parseSpendCsv(good.replace(',USD',',EUR'),'spend',PILOT_KEY,'reviewed_ads_export_1'),/CURRENCY_UNSUPPORTED/);
  assert.throws(()=>parseSpendCsv(good.replace(',100,2,',',1,2,'),'spend',PILOT_KEY,'reviewed_ads_export_1'),/CLICKS_EXCEED/);
  assert.throws(()=>parseSpendCsv(good.replace(',100,2,',',=1+1,2,'),'spend',PILOT_KEY,'reviewed_ads_export_1'),/CSV_ROW_INVALID/);
  assert.throws(()=>parseSpendCsv(good+'\n24457739017,2026-11-09,100,2,1,USD','spend',PILOT_KEY,'reviewed_ads_export_1'),/CSV_DUPLICATE_CAMPAIGN_DAY/);
  assert.throws(()=>parseSpendCsv(good,'spend','google:cpc:unregistered','reviewed_ads_export_1'),/CAMPAIGN_NOT_REGISTERED/);
  const partialToday='campaign_id,date,impressions,clicks,spend,currency,coverage\n24457739017,2026-11-10,10,1,1.00,USD,partial';
  assert.equal(parseSpendCsv(partialToday,'spend',PILOT_KEY,'reviewed_ads_export_1')[0].coverage,'partial');
  assert.throws(()=>parseSpendCsv(partialToday.replace(',partial',',complete'),'spend',PILOT_KEY,'reviewed_ads_export_1'),/CSV_DAY_NOT_COMPLETE/);
  assert.throws(()=>parseSpendCsv('campaign_id,date,impressions,clicks,spend,currency,coverage,coverage_end_utc\n24457739017,2026-11-10,10,1,1.00,USD,partial,2026-11-11T06:00:00.001Z','spend',PILOT_KEY,'reviewed_ads_export_1'),/CSV_COVERAGE_END_INVALID/);
  const orderCsv='order_id,amount,currency,effective_at,source_ref,authority,coverage\no_123,8.18,USD,2026-11-09T12:00:00.000Z,invoice_123,actual,complete';
  assert.equal(parseSpendCsv(orderCsv,'supplier',PILOT_KEY,'')[0].kind,'supplier');
  assert.throws(()=>parseSpendCsv(orderCsv.replace(',USD,',',CAD,'),'supplier',PILOT_KEY,''),/CURRENCY_UNSUPPORTED/);
});
test('reviewed cost import requires admin origin, deduplicates and refuses conflicting amounts',async()=>{
  process.env.ADMIN_SESSION_SIGNING_KEY='offline_attribution_admin_signing_key_123456789';
  process.env.NEXT_PUBLIC_APP_URL='http://localhost:3000';
  const token=generateAdminSessionToken();
  const request=(records:unknown[],requestId:string,authenticated=true,origin=true)=>new NextRequest('http://localhost:3000/api/admin/console/cost-evidence',{method:'POST',headers:{'Content-Type':'application/json',...(authenticated?{Cookie:`docketstamp_admin_session=${token}`} : {}),...(origin?{Origin:'http://localhost:3000'}:{})},body:JSON.stringify({records,requestId,reason:'Reviewed offline provider evidence'})});
  assert.equal((await POST(request([record],'request_no_auth',false))).status,401);
  assert.equal((await POST(request([record],'request_no_origin',true,false))).status,403);
  assert.equal((await POST(request([record],'request_valid_1'))).status,200);
  const repeated=await POST(request([record],'request_valid_2'));
  assert.equal(repeated.status,200);
  assert.equal((await repeated.json()).duplicates,1);
  assert.equal((await firestoreDb.collection('cost_records_v1').get()).size,1);
  assert.equal((await POST(request([{...record,amountMinor:500}],'request_conflict'))).status,400);
  assert.equal((await POST(request([{...record,amountMinor:500}],'request_valid_1'))).status,409);
  const correction=await POST(request([{...record,amountMinor:500,revision:2}],'request_correction_2'));
  assert.equal(correction.status,200);
  assert.equal((await firestoreDb.collection('cost_records_v1').get()).size,2);
  const overlap=await POST(request([{...record,effectiveAt:'2026-11-01T12:00:00.000Z',coverageStartUtc:'2026-11-01T12:00:00.000Z',coverageEndUtc:'2026-11-02T12:00:00.000Z'}],'request_overlap_3'));
  assert.equal(overlap.status,400);
  assert.equal((await POST(request([{...record,currency:'EUR'}],'request_mixed_currency'))).status,400);
  await firestoreDb.collection('orders').doc('cost_order_1').set({id:'cost_order_1',environment:'local'});
  const orderCost={kind:'supplier',orderId:'cost_order_1',amountMinor:818,currency:'USD',effectiveAt:'2026-11-09T12:00:00.000Z',sourceRef:'invoice_cost_1',authority:'actual',coverage:'complete'};
  assert.equal((await POST(request([orderCost],'request_order_cost_1'))).status,200);
  assert.equal((await POST(request([{...orderCost,amountMinor:900,revision:2}],'request_order_cost_correction'))).status,200);
  await firestoreDb.collection('orders').doc('foreign_cost_order').set({id:'foreign_cost_order',environment:'staging'});
  assert.equal((await POST(request([{...orderCost,orderId:'foreign_cost_order',sourceRef:'foreign_invoice'}],'request_foreign_order_cost'))).status,400);
});
