export function getVerifiedRecipientsByCategory(
  category: string
): VerifiedRecipientEntry[] {
  const normalizedCategory = CATEGORY_MAP[category] || category;
  return VERIFIED_RECIPIENTS.filter((r) => {
    return (
      r.category === normalizedCategory ||
      (category === 'CREDIT_BUREAU' && r.category === 'credit_bureau') ||
      (category === 'COLLECTION_AGENCY' && r.category === 'debt_collector') ||
      (category === 'HOME_SECURITY' && r.id.startsWith('srv_')) ||
      (category === 'TELECOM' && r.id.startsWith('tel_')) ||
      (category === 'INSURANCE' && r.id.startsWith('ins_')) ||
      (category === 'PEST_CONTROL' && (r.id === 'srv_tmx' || r.id === 'srv_ork')) ||
      ((category === 'TECH_HARDWARE' || category === 'TECH_HARDWARE_LEGAL' || category === 'LEGAL') && r.category === 'tech_hardware_legal')
    );
  });
}

export function searchVerifiedRecipients(
  query?: string,
  category?: string
): VerifiedRecipientEntry[] {
  if (!query && !category) return VERIFIED_RECIPIENTS;

  const normalized = (query || '').trim().toLowerCase();
  const normalizedCategory = category ? (CATEGORY_MAP[category] || category) : undefined;

  return VERIFIED_RECIPIENTS.filter((item) => {
    assertNonFitnessEntity(item.brandName);
    assertNonFitnessEntity(item.formalRecipientLine);

    if (normalizedCategory) {
      const match =
        item.category === normalizedCategory ||
        (category === 'CREDIT_BUREAU' && item.category === 'credit_bureau') ||
        (category === 'COLLECTION_AGENCY' && item.category === 'debt_collector') ||
        (category === 'TELECOM' && item.id.startsWith('tel_')) ||
        (category === 'INSURANCE' && item.id.startsWith('ins_')) ||
        ((category === 'TECH_HARDWARE' || category === 'TECH_HARDWARE_LEGAL' || category === 'LEGAL') && item.category === 'tech_hardware_legal');
      if (!match) return false;
    }

    if (!normalized) return true;

    return (
      item.brandName.toLowerCase().includes(normalized) ||
      item.formalRecipientLine.toLowerCase().includes(normalized) ||
      item.city.toLowerCase().includes(normalized) ||
      item.state.toLowerCase().includes(normalized) ||
      item.id.toLowerCase().includes(normalized) ||
      (item.department && item.department.toLowerCase().includes(normalized))
    );
  });
}
