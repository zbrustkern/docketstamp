export function getStateStatute(stateCode: string): StateStatuteEntry | undefined {
  if (!stateCode) return undefined;
  return STATE_STATUTES[stateCode.trim().toUpperCase()];
}

export const getSecurityDepositStatute = getStateStatute;

export function getAllStateStatutes(): StateStatuteEntry[] {
  return Object.values(STATE_STATUTES);
}

export function formatStatuteCitation(stateCode: string): string {
  const statute = getStateStatute(stateCode);
  if (!statute) return 'Applicable State Residential Landlord-Tenant Act';
  return `${statute.statuteCitation} (${statute.returnDeadlineLabel || `${statute.returnDeadlineDays}-Day Statutory Deadline`})`;
}
