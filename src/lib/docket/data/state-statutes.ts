export function getStateStatute(stateCode: string): SecurityDepositStatute | undefined {
  if (!stateCode) return undefined;
  return STATE_SECURITY_DEPOSIT_STATUTES[stateCode.trim().toUpperCase()];
}

export const getSecurityDepositStatute = getStateStatute;

export function getAllStateStatutes(): SecurityDepositStatute[] {
  return Object.values(STATE_SECURITY_DEPOSIT_STATUTES);
}

export function formatStatuteCitation(stateCode: string): string {
  const statute = getStateStatute(stateCode);
  if (!statute) return 'Applicable State Residential Landlord-Tenant Act';
  return `${statute.statutoryCitation} (${statute.returnDeadlineDays}-Day Statutory Deadline)`;
}
